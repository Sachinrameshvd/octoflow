#!/usr/bin/env python3
"""Deterministic lockfile and constraints generator for OctoFlow.

Generates:
- requirements.lock: pinned dependencies with full provenance comments (pip-compile style).
- constraints.txt: pip constraints format.

Can be run directly or via `make lock`.
"""

import sys
from pathlib import Path
from packaging.requirements import Requirement
import importlib.metadata as im

try:
    import tomllib
except ModuleNotFoundError:
    import tomli as tomllib  # type: ignore


def generate_lockfile(workspace_dir: str = ".") -> Path:
    ws = Path(workspace_dir).resolve()
    pyproject_path = ws / "pyproject.toml"
    if not pyproject_path.exists():
        raise FileNotFoundError(f"Missing {pyproject_path}")

    pyproject = tomllib.loads(pyproject_path.read_text(encoding="utf-8"))
    base_deps = pyproject.get("project", {}).get("dependencies", [])
    dev_deps = pyproject.get("project", {}).get("optional-dependencies", {}).get("dev", [])
    direct_req_strings = base_deps + dev_deps

    # Installed distributions lookup: normalized-name -> (canonical_name, version)
    installed: dict[str, tuple[str, str]] = {}
    for d in im.distributions():
        name = d.metadata.get("Name")
        if name:
            norm = name.lower().replace("_", "-")
            installed[norm] = (name, d.version)

    # Dependency traversal
    def get_dependencies(pkg_norm: str) -> list[str]:
        canonical_name, _ = installed.get(pkg_norm, (pkg_norm, ""))
        try:
            req_strings = im.requires(canonical_name) or []
        except Exception:
            return []
        
        deps: list[str] = []
        for r_str in req_strings:
            try:
                req = Requirement(r_str)
                # Discard optional extras (e.g. testing, docs of third-party libraries)
                if req.marker and not req.marker.evaluate({"extra": ""}):
                    continue
                deps.append(req.name.lower().replace("_", "-"))
            except Exception:
                continue
        return deps

    # Build provenance graph
    provenance: dict[str, set[str]] = {}
    queue: list[tuple[str, str]] = []

    for r_str in direct_req_strings:
        try:
            req = Requirement(r_str)
            norm = req.name.lower().replace("_", "-")
            queue.append((norm, "octoflow"))
        except Exception:
            continue

    visited: set[str] = set()
    while queue:
        pkg, parent = queue.pop(0)
        provenance.setdefault(pkg, set()).add(parent)
        if pkg in visited:
            continue
        visited.add(pkg)

        for child in get_dependencies(pkg):
            if child in installed and child not in visited:
                queue.append((child, pkg))

    # Known fallbacks if not locally in current venv
    fallbacks = {
        "pre-commit": ("pre-commit", "4.1.0"),
        "types-requests": ("types-requests", "2.32.0.20241016"),
        "pyyaml": ("PyYAML", "6.0.3"),
        "virtualenv": ("virtualenv", "20.29.2"),
        "cfgv": ("cfgv", "3.4.0"),
        "identify": ("identify", "2.6.8"),
        "nodeenv": ("nodeenv", "1.9.1"),
        "distlib": ("distlib", "0.3.9"),
    }

    lock_lines = [
        "#",
        "# This file is autogenerated by OctoFlow lock generator (make lock)",
        f"# Target Python: >=3.10, compatible with 3.10 and 3.12",
        f"# Generated with Python {sys.version.split()[0]} on {sys.platform}",
        "#",
        "# To update, run:",
        "#",
        "#    make lock",
        "#",
        "",
    ]

    constraint_lines = [
        "# OctoFlow pip constraints file",
        f"# Generated with Python {sys.version.split()[0]}",
        "",
    ]

    all_keys = sorted(provenance.keys())
    for k in all_keys:
        if k in installed:
            cname, ver = installed[k]
        elif k in fallbacks:
            cname, ver = fallbacks[k]
        else:
            continue

        parents = sorted(provenance[k])
        via_str = ", ".join(parents)
        lock_lines.append(f"{cname}=={ver}")
        lock_lines.append(f"    # via {via_str}")
        constraint_lines.append(f"{cname}=={ver}")

    lock_file = ws / "requirements.lock"
    lock_file.write_text("\n".join(lock_lines) + "\n", encoding="utf-8")

    constraints_file = ws / "constraints.txt"
    constraints_file.write_text("\n".join(constraint_lines) + "\n", encoding="utf-8")

    print(f"✔ Generated {lock_file.relative_to(ws)} ({len(all_keys)} packages locked)")
    print(f"✔ Generated {constraints_file.relative_to(ws)}")
    return lock_file


if __name__ == "__main__":
    generate_lockfile()
