def format_type(param_type: Any) -> str:
    """Format click/typer parameter type for markdown display."""
    t_str = str(param_type)
    if "Path" in t_str:
        return "path"
    if "int" in t_str.lower() or "integer" in t_str.lower():
        return "int"
    if "float" in t_str.lower():
        return "float"
    if "bool" in t_str.lower() or "boolean" in t_str.lower():
        return "bool"
    if "choice" in t_str.lower():
        return "choice"
    return "str"


def format_default(val: Any) -> str:
    """Format default parameter values for display."""
    if val is None:
        return "`None`"
    if isinstance(val, bool):
        return f"`{str(val).lower()}`"
    if isinstance(val, (int, float)):
        return f"`{val}`"
    if isinstance(val, str):
        if not val:
            return '`""`'
        return f"`{val}`"
    return f"`{val}`"


def generate_cli_reference() -> str:
    """Generate docs/reference/cli.md from Typer/Click command tree."""
    import typer.main
    import octoflow.cli

    click_cmd = typer.main.get_command(octoflow.cli.app)
    commands = click_cmd.commands

    lines = [
        HEADER_NOTICE.strip(),
        "",
        "# OctoFlow CLI Command Reference",
        "",
        "This document is automatically generated from the registered Typer command tree in `octoflow/cli.py`.",
        "",
        "OctoFlow exposes three CLI entrypoint aliases with identical semantics:",
        "- `octoflow <command>`: Canonical command invocation.",
        "- `octo <command>`: Short alias.",
        "- `octos <command>`: Multi-agent plural alias.",
        "",
        "---",
        "",
        "## Master Command Directory",
        "",
        "| Command | Description | Syntax |",
        "| :--- | :--- | :--- |",
    ]

    for name in sorted(commands.keys()):
        cmd = commands[name]
        raw_help = (cmd.help or cmd.short_help or "").strip()
        first_line = raw_help.split("\n")[0].replace("|", "\\|") if raw_help else "No description available."
        # Clean experimental badges
        first_line = first_line.replace("\\[experimental]", "(Experimental)")
        lines.append(f"| [`octoflow {name}`](#octoflow-{name}) | {first_line} | `octoflow {name} [OPTIONS]` |")

    lines.extend([
        "",
        "---",
        "",
        "## Command Details",
        "",
    ])

    for name in sorted(commands.keys()):
        cmd = commands[name]
        raw_help = (cmd.help or cmd.short_help or "").strip()
        desc = raw_help if raw_help else "No detailed description provided."

        lines.extend([
            f"### <a id=\"octoflow-{name}\"></a>`octoflow {name}`",
            "",
            desc,
            "",
            "**Usage:**",
            "```bash",
            f"octoflow {name} [OPTIONS]",
            "```",
            "",
        ])

        # Separate params into arguments and options
        args = [p for p in cmd.params if getattr(p, "param_type_name", "") == "argument"]
        opts = [p for p in cmd.params if getattr(p, "param_type_name", "") == "option"]

        if args:
            lines.extend([
                "#### Arguments",
                "",
                "| Argument | Type | Required | Default | Description |",
                "| :--- | :--- | :---: | :--- | :--- |",
            ])
            for arg in args:
                arg_name = arg.name
                arg_type = format_type(arg.type)
                req = "Yes" if getattr(arg, "required", False) else "No"
                def_val = format_default(arg.default)
                help_text = (getattr(arg, "help", "") or "").replace("|", "\\|")
                lines.append(f"| `{arg_name}` | `{arg_type}` | {req} | {def_val} | {help_text} |")
            lines.append("")

        if opts:
            lines.extend([
                "#### Options",
                "",
                "| Option | Type | Default | Description |",
                "| :--- | :--- | :--- | :--- |",
            ])
            for opt in opts:
                flags = ", ".join(f"`{f}`" for f in opt.opts)
                if getattr(opt, "secondary_opts", None):
                    flags += ", " + ", ".join(f"`{f}`" for f in opt.secondary_opts)
                opt_type = format_type(opt.type)
                def_val = format_default(opt.default)
                help_text = (getattr(opt, "help", "") or "").replace("|", "\\|")
                lines.append(f"| {flags} | `{opt_type}` | {def_val} | {help_text} |")
            lines.append("")

        # Handle subcommands (e.g. config group)
        if hasattr(cmd, "commands") and cmd.commands:
            lines.extend([
                "#### Subcommands",
                "",
                "| Subcommand | Syntax | Description |",
                "| :--- | :--- | :--- |",
            ])
            for sub_name, sub_cmd in sorted(cmd.commands.items()):
                sub_help = (sub_cmd.help or sub_cmd.short_help or "").strip().split("\n")[0].replace("|", "\\|")
                lines.append(f"| `{sub_name}` | `octoflow {name} {sub_name}` | {sub_help} |")
            lines.append("")

        lines.append("---")
        lines.append("")

    return "\n".join(lines).strip() + "\n"


