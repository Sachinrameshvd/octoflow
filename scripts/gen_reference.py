GENERATORS = {
    "cli.md": generate_cli_reference,
    "config.md": generate_config_reference,
    "errors.md": generate_errors_reference,
    "exit-codes.md": generate_exit_codes_reference,
}


def write_references(output_dir: Path | None = None) -> dict[str, str]:
    """Generate all reference files and write to target directory."""
    target_dir = (output_dir or (REPO_ROOT / "docs" / "reference")).resolve()
    target_dir.mkdir(parents=True, exist_ok=True)

    generated: dict[str, str] = {}
    for filename, gen_func in GENERATORS.items():
        content = gen_func()
        out_path = target_dir / filename
        out_path.write_text(content, encoding="utf-8")
        generated[filename] = content

    return generated


def check_references(target_dir: Path | None = None) -> list[str]:
    """Compare on-disk reference files against generator output. Returns list of diffs."""
    ref_dir = (target_dir or (REPO_ROOT / "docs" / "reference")).resolve()
    diffs: list[str] = []

    for filename, gen_func in GENERATORS.items():
        expected = gen_func()
        file_path = ref_dir / filename
        if not file_path.is_file():
            diffs.append(f"Missing reference file: {file_path.relative_to(REPO_ROOT if REPO_ROOT in file_path.parents else ref_dir)}")
            continue

        actual = file_path.read_text(encoding="utf-8")
        if actual != expected:
            diff = difflib.unified_diff(
                actual.splitlines(keepends=True),
                expected.splitlines(keepends=True),
                fromfile=f"a/{filename} (on disk)",
                tofile=f"b/{filename} (generated)",
                n=3,
            )
            diff_text = "".join(diff)
            diffs.append(f"Stale reference file '{filename}':\n{diff_text}")

    return diffs


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate OctoFlow reference documentation from code.")
    parser.add_argument("--check", action="store_true", help="Check if references are up to date without overwriting.")
    parser.add_argument("--output-dir", type=Path, default=None, help="Custom output directory.")
    args = parser.parse_args()

    target_dir = args.output_dir or (REPO_ROOT / "docs" / "reference")

    if args.check:
        print(f"◈ Checking generated references in: {target_dir}")
        diffs = check_references(target_dir)
        if diffs:
            print(f"\n✖ Found {len(diffs)} stale reference document(s):\n")
            for diff in diffs:
                print(diff)
            print("\nRun 'make docs-ref' to regenerate reference documentation.")
            return 1
        print("✔ All generated reference documents are up-to-date!")
        return 0

    print(f"◈ Generating reference documentation into: {target_dir}")
    generated = write_references(target_dir)
    for fname in generated:
        print(f"  • Generated {fname}")
    print("\n✔ All reference documents generated successfully!")
    return 0


if __name__ == "__main__":
    sys.exit(main())
